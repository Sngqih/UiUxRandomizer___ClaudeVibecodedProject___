// Downloads every font used by the randomizer (the families/weights in
// src/lib/fonts.js) from Google Fonts as local .woff2 files and generates a
// self-hosted @font-face stylesheet at src/assets/fonts/fonts.css.
//
// Run with: npm run fonts   (needs internet; one-time — commit the result).
// After this, the app loads fonts locally and works fully offline.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'src', 'assets', 'fonts');
mkdirSync(OUT, { recursive: true });

const { FONT_PAIRS } = await import(pathToFileURL(join(root, 'src', 'lib', 'fonts.js')).href);

// A modern UA so Google serves woff2.
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36';
const KEEP_SUBSETS = new Set(['latin', 'latin-ext']);

// family -> set of weights (merged across all pairings).
const families = new Map();
for (const p of FONT_PAIRS) {
  for (const [fam, weights] of [[p.h[0], p.hw], [p.b[0], p.bw]]) {
    if (!families.has(fam)) families.set(fam, new Set());
    weights.split(';').forEach((w) => families.get(fam).add(w.trim()));
  }
}

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');

let css = '/* Self-hosted fonts — generated by scripts/fetch-fonts.mjs. Do not edit by hand. */\n';
const savedFiles = new Set();
let okFamilies = 0;
let fileCount = 0;
const failed = [];

for (const [fam, weightSet] of families) {
  const weights = [...weightSet].sort((a, b) => Number(a.split(' ')[0]) - Number(b.split(' ')[0]));
  const apiUrl = `https://fonts.googleapis.com/css2?family=${fam.replace(/ /g, '+')}:wght@${weights.join(';')}&display=swap`;

  let sheet;
  try {
    const res = await fetch(apiUrl, { headers: { 'User-Agent': UA } });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    sheet = await res.text();
  } catch (err) {
    failed.push(`${fam} (css: ${err.message})`);
    continue;
  }

  const blockRe = /\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]+)\}/g;
  let match;
  let got = 0;
  while ((match = blockRe.exec(sheet))) {
    const subset = match[1];
    if (!KEEP_SUBSETS.has(subset)) continue;
    const body = match[2];
    const weight = (body.match(/font-weight:\s*([^;]+);/) || [])[1]?.trim() || '400';
    const style = (body.match(/font-style:\s*([^;]+);/) || [])[1]?.trim() || 'normal';
    const srcUrl = (body.match(/url\(([^)]+\.woff2)\)/) || [])[1];
    if (!srcUrl) continue;

    const fname = `${slug(fam)}-${weight.replace(/\s+/g, '_')}${style === 'italic' ? '-italic' : ''}-${subset}.woff2`;
    if (!savedFiles.has(fname)) {
      try {
        const fr = await fetch(srcUrl, { headers: { 'User-Agent': UA } });
        if (!fr.ok) throw new Error(`HTTP ${fr.status}`);
        writeFileSync(join(OUT, fname), Buffer.from(await fr.arrayBuffer()));
        savedFiles.add(fname);
        fileCount++;
      } catch (err) {
        failed.push(`${fam} ${weight} (file: ${err.message})`);
        continue;
      }
    }
    css +=
      `@font-face{font-family:'${fam}';font-style:${style};font-weight:${weight};` +
      `font-display:swap;src:url('./${fname}') format('woff2');}\n`;
    got++;
  }
  if (got) {
    okFamilies++;
    process.stdout.write(`✓ ${fam} (${got})\n`);
  } else {
    failed.push(`${fam} (no latin block parsed)`);
  }
}

writeFileSync(join(OUT, 'fonts.css'), css);
console.log(`\nDone: ${okFamilies}/${families.size} families, ${fileCount} files written to src/assets/fonts/`);
if (failed.length) console.warn(`\nFell back (will use system fonts):\n  - ${failed.join('\n  - ')}`);
